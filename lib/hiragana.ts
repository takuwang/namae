const exactReadings: Record<string, string> = {
  쇼쿠: 'しょく',
  유키: 'ゆき',
};

export function toHiragana(reading: string) {
  if (exactReadings[reading]) return exactReadings[reading];
  return Array.from(reading).map((syllable) => syllables[syllable] ?? syllable).join('');
}
